export const getReasonLabel = (
  key: string | null | undefined,
  language: DayOffLanguage = "en",
): string => {
  if (!key) return "";
  const map = dayOffReasonLabels[language] ?? dayOffReasonLabels.en;
  return (map as Record<string, string>)[key] ?? key;
};
